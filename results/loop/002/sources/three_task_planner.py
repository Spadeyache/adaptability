"""Choose a capped shove from autonomous predictions at a measured ready state."""
import numpy as np
import torch


@torch.no_grad()
def choose_force(model, initial_state, direction, target_distance_m, candidates, action_sequences, *, z,
                 force_cap_n=4., fallback_force_n=2.5, cube_xy=(19, 20), cube_velocity=(28, 29, 30)):
    """Choose the force whose predicted endpoint is closest to a specified XY target.

    Action sequences must be generated by the same open-loop command function
    used for execution. The only measured state supplied here is the ready state.
    A full predicted state feeds each later step. Every finite endpoint remains
    eligible, including one with high predicted terminal velocity. If all
    candidates become nonfinite, the declared fallback is selected and flagged.
    """
    initial = np.asarray(initial_state, dtype=np.float32)
    forces = np.asarray(candidates, dtype=np.float64)
    commands = np.asarray(action_sequences, dtype=np.float32)
    heading = np.asarray(direction, dtype=np.float64)
    state_dim = len(model.model.delta_mean)
    action_dim = len(model.model.input_mean) - state_dim
    if initial.shape != (state_dim,) or not np.isfinite(initial).all():
        raise ValueError('Expected one finite measured ready state')
    if forces.ndim != 1 or not len(forces) or not np.isfinite(forces).all() or len(np.unique(forces)) != len(forces):
        raise ValueError('Force candidates must be distinct finite scalars')
    if not np.isfinite(force_cap_n) or force_cap_n <= 0 or (forces < 0).any() or (forces > force_cap_n).any():
        raise ValueError('Candidates must lie between zero and the declared force cap')
    fallback = np.flatnonzero(np.isclose(forces, fallback_force_n, rtol=0, atol=1e-8))
    if len(fallback) != 1:
        raise ValueError('The declared fallback force must be included exactly once among the candidates')
    if (commands.ndim != 3 or commands.shape[0] != len(forces) or not commands.shape[1]
            or commands.shape[2] != action_dim or not np.isfinite(commands).all()):
        raise ValueError('Expected one finite command sequence per candidate, with a shared horizon')
    if heading.shape != (2,) or not np.isfinite(heading).all() or np.linalg.norm(heading) == 0:
        raise ValueError('Expected a finite nonzero planar shove direction')
    if not np.isfinite(target_distance_m) or target_distance_m < 0:
        raise ValueError('Target distance must be finite and nonnegative')
    heading = heading / np.linalg.norm(heading)
    xy, velocity = np.asarray(cube_xy, dtype=int), np.asarray(cube_velocity, dtype=int)
    if xy.shape != (2,) or (xy < 0).any() or (xy >= state_dim).any():
        raise ValueError('Expected two valid state columns for the cube XY position')
    if velocity.shape != (3,) or (velocity < 0).any() or (velocity >= state_dim).any():
        raise ValueError('Expected three valid state columns for cube linear velocity')
    target = initial[xy].astype(np.float64) + target_distance_m * heading
    states = torch.as_tensor(initial, device=model.device).expand(len(forces), -1).clone()
    actions = torch.as_tensor(commands, device=model.device)
    latent = model._latent(z).expand(len(forces), -1)
    divergence = torch.full((len(forces),), -1, dtype=torch.long, device=model.device)
    for step in range(commands.shape[1]):
        predicted = model.model.advance(states, actions[:, step], latent)
        finite = torch.isfinite(predicted).all(dim=1)
        active = divergence < 0
        divergence = torch.where(active & ~finite, step, divergence)
        states = torch.where((active & finite)[:, None], predicted, states)
    predictions, failed = states.cpu().numpy(), divergence.cpu().numpy()
    valid = failed < 0
    errors = np.full(len(forces), np.inf, dtype=np.float64)
    difference = predictions[valid][:, xy].astype(np.float64) - target
    errors[valid] = np.hypot(difference[:, 0], difference[:, 1])
    chosen = int(np.argmin(errors)) if valid.any() else int(fallback[0])
    selected_valid = bool(valid[chosen])
    return dict(
        selected_force_n=float(forces[chosen]), selected_candidate_index=chosen,
        planner_status='finite_prediction' if selected_valid else 'all_nonfinite_midpoint_fallback',
        target_xy=target.tolist(), direction=heading.tolist(), target_distance_m=float(target_distance_m),
        predicted_endpoint_xy=predictions[chosen, xy].astype(float).tolist() if selected_valid else None,
        predicted_target_error_m=float(errors[chosen]) if selected_valid else None,
        predicted_final_speed_m_s=float(np.linalg.norm(predictions[chosen, velocity].astype(np.float64)))
        if selected_valid else None,
        valid_candidates=int(valid.sum()), candidate_count=len(forces),
        candidate_valid_fraction=float(valid.mean()), candidate_forces_n=forces.tolist(),
        candidate_target_errors_m=[float(error) if okay else None for error, okay in zip(errors, valid)],
        candidate_divergence_steps=[None if step < 0 else int(step) for step in failed],
        force_cap_n=float(force_cap_n), fallback_force_n=float(fallback_force_n),
        rollout_steps=commands.shape[1],
    )
